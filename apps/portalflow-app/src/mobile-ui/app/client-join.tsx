"use client";

import { useEffect, useState } from 'react';
import { View, Text, StyleSheet, TouchableOpacity, ScrollView, ActivityIndicator } from 'react-native';
import { useLocalSearchParams, useRouter } from 'expo-router';
import { StatusBar } from 'expo-status-bar';
import { getFirmClientInviteInfo } from '@/lib/firm-clients';

const FEATURES = [
  { kicker: 'Secure storage', title: 'Bank-level security', body: 'Your sensitive financial documents are encrypted and stored in a private vault, so your privacy is always protected.' },
  { kicker: 'One-tap upload', title: 'Snap & sync', body: 'No more paper piles. Capture receipts on the go and sync them instantly with our team from your phone.' },
  { kicker: 'Transparent progress', title: 'Real-time collaboration', body: 'Stay updated on your filing status and exchange notes with us directly—no more repeated calls to check in.' },
  { kicker: 'Permanent record', title: 'Lifetime tax history', body: 'Access your historical returns and receipts anytime, anywhere for future reference and reuse.' },
];

export default function ClientJoinScreen() {
  const router = useRouter();
  const params = useLocalSearchParams<{ token?: string; firmName?: string }>();
  const token = (typeof params.token === 'string' ? params.token : '').trim();
  const firmNameParam = typeof params.firmName === 'string' ? params.firmName : '';
  const [firmName, setFirmName] = useState(firmNameParam || 'Your tax firm');
  const [invalid, setInvalid] = useState(false);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (!token) {
      setInvalid(true);
      setLoading(false);
      return;
    }
    getFirmClientInviteInfo(token).then(({ info, error }) => {
      if (error || !info) setInvalid(true);
      else if (info.firmName) setFirmName(info.firmName);
      setLoading(false);
    });
  }, [token]);

  return (
    <ScrollView contentContainerStyle={styles.page}>
      <StatusBar style="dark" />
      <View style={styles.card}>
        <Text style={styles.firm}>{firmName}</Text>
        <Text style={styles.invite}>invites you to join the Secure Portal</Text>
        <Text style={styles.lead}>Securely track tax filings and collaborate with your professional.</Text>
        {loading ? <ActivityIndicator color="#6C5CE7" /> : invalid ? (
          <Text style={styles.invalid}>This invite link has expired or is no longer valid. Please ask your tax professional to send a new invite.</Text>
        ) : (
          <TouchableOpacity
            style={styles.button}
            onPress={() => router.push({ pathname: '/portal/join', params: { token } })}
          >
            <Text style={styles.buttonText}>Continue</Text>
          </TouchableOpacity>
        )}
        <View style={styles.features}>
          {FEATURES.map((item) => (
            <View key={item.title} style={styles.feature}>
              <Text style={styles.kicker}>{item.kicker}</Text>
              <Text style={styles.featureTitle}>{item.title}</Text>
              <Text style={styles.featureBody}>{item.body}</Text>
            </View>
          ))}
        </View>
      </View>
      <Text style={styles.footer}>This secure link was generated by {firmName} for official tax collaboration with you, powered by Portalflow.</Text>
    </ScrollView>
  );
}

const styles = StyleSheet.create({
  page: { flexGrow: 1, backgroundColor: '#F8FAFC', alignItems: 'center', padding: 24 },
  card: { width: '100%', maxWidth: 440, backgroundColor: '#fff', borderRadius: 20, padding: 24, borderWidth: 1, borderColor: '#F1F5F9' },
  firm: { textAlign: 'center', color: '#6C5CE7', fontSize: 20, fontWeight: '700', borderBottomWidth: 2, borderBottomColor: '#6C5CE7', alignSelf: 'center', paddingHorizontal: 16, marginBottom: 10 },
  invite: { textAlign: 'center', fontWeight: '600', color: '#334155', marginBottom: 8 },
  lead: { textAlign: 'center', color: '#64748B', fontSize: 13, marginBottom: 16 },
  button: { backgroundColor: '#0F172A', borderRadius: 12, paddingVertical: 14, alignItems: 'center', marginBottom: 16 },
  buttonText: { color: '#fff', fontWeight: '700' },
  invalid: { color: '#B91C1C', textAlign: 'center', marginBottom: 16 },
  features: { borderTopWidth: 1, borderTopColor: '#F1F5F9', paddingTop: 12 },
  feature: { marginBottom: 12 },
  kicker: { color: '#6C5CE7', fontSize: 11, fontWeight: '700', textTransform: 'uppercase' },
  featureTitle: { color: '#1E293B', fontWeight: '700', marginTop: 2 },
  featureBody: { color: '#64748B', fontSize: 12, lineHeight: 18, marginTop: 2 },
  footer: { marginTop: 16, maxWidth: 360, textAlign: 'center', color: '#94A3B8', fontSize: 11, lineHeight: 16 },
});
